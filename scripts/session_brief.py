#!/usr/bin/env python3
"""M62 — generate the session brief instead of remembering it.

Why this exists: the 125B pays a fixed prefill cost per session (measured: 596 tok -> 1.83 s,
44,446 tok -> 15.4 s, i.e. ~0.35 ms per extra token), so a 14 KB NEXT_PROMPT costs ~1.4 s of
prefill — nothing. What actually burns a local model's budget is *stumbling*: re-deriving live
state from prose, discovering mid-run that the box is in a dead shape, or hand-parsing a trace.
So the brief carries only machine-truth that changes every session, and everything else stays
in the skill (loaded on demand, gate-synced).

  python3 scripts/session_brief.py            # print (<= 4000 chars)
  python3 scripts/session_brief.py --write    # also rewrite BRIEF.md

Exit 0 if the box is READY, 1 if blocked — the brief doubles as the pre-flight.
"""
import argparse, datetime, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import accept_ready as AR
import m55_boundary as M
import m56_build as B
import evidence as E

CAP = 4000


def next_pick():
    try:
        txt = open(os.path.join(ROOT, "NEXT_PROMPT.md"), encoding="utf-8").read()
    except OSError:
        return "(NEXT_PROMPT.md missing)"
    m = re.search(r"^## THE PICK[^\n]*\n+([^\n]+)", txt, re.M)
    return (m.group(1).strip() if m else "(no '## THE PICK' section)")[:160]


def conflicts():
    try:
        txt = open(os.path.join(ROOT, "NAMED.md"), encoding="utf-8").read()
    except OSError:
        return []
    return [ln.strip()[len("CONFLICT:"):].strip() for ln in txt.splitlines()
            if ln.startswith("CONFLICT:")]


def uncited():
    ev = os.path.join(ROOT, "evidence")
    try:
        pats = E.load_cites()
    except Exception:
        return None
    n = mb = 0
    for f in os.listdir(ev):
        p = os.path.join(ev, f)
        if os.path.isfile(p) and not E.is_cited(f, pats):
            n += 1
            mb += os.path.getsize(p)
    return n, mb / 1e6


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--no-screen", action="store_true")
    a = ap.parse_args()

    pid = M.find_pid()
    budget = sum(os.path.getsize(os.path.join(d, f)) for d, _, fs in os.walk(os.path.join(ROOT, "evidence"))
                 for f in fs) / 1e6
    rows, tl, screen = [], {}, ""
    if pid and os.path.exists(f"/proc/{pid}"):
        with open(f"/proc/{pid}/mem", "rb", 0) as m:
            player, rows = AR.collect(m)
            tl = M.timeline_row(m)
        if not a.no_screen:
            screen = AR.screen_class()[0]
        res = AR.decide(rows, budget_mb=budget, gdb_n=AR.gdb_count(), screen=screen)
    else:
        res = dict(ready=False, verdict="BLOCKED", fix="terran.exe not running — m54a_load.py --relaunch",
                   reasons=[], target=None)

    L = []
    L.append(f"SMAC BRIEF {datetime.datetime.now():%Y-%m-%d %H:%M}  ({res['verdict']})")
    if tl:
        L.append(f"box: year {tl['year']} round {tl['round']} cur_player {tl['cur_player']} "
                 f"screen {screen or 'unchecked'}  evidence {budget:.1f} MB")
    for r in rows:
        L.append(f"  i{r['i']:>3} {str(r['name'])[:20]:20} min {r['minerals']:>4} credit {r['credit']:>3} "
                 f"pend {r['pending']:>2} head {r['head']:>3} price {r['price']:>3}")
    if res["fix"]:
        L.append("FIX: " + str(res["fix"]))
    elif res.get("target"):
        L.append(f"RUN: scripts/m56_build.py --ui-queued {res['target_index']} --boundaries 10 "
                 f"--timeout 400 --no-poke-hold"
                 + ("   (TIGHT horizon — reload preferred)" if res.get("target_tight") else ""))
    for c in conflicts():
        L.append("CONFLICT: " + c[:150])
    u = uncited()
    if u:
        L.append(f"uncited evidence: {u[0]} files {u[1]:.1f} MB — scripts/evidence.py audit --delete")
    L.append("NEXT: " + next_pick())
    L.append("first: python3 scripts/accept_ready.py; python3 scripts/test_accept_ready.py; "
             "python3 scripts/gate.py --base main")
    out = "\n".join(L)
    if len(out) > CAP:
        out = out[:CAP] + "\n…(truncated)"
    print(out)
    if a.write:
        with open(os.path.join(ROOT, "BRIEF.md"), "w") as f:
            f.write("<!-- generated by scripts/session_brief.py; do not hand-edit -->\n\n"
                    + out + "\n")
    return 0 if res["ready"] else 1


if __name__ == "__main__":
    sys.exit(main())
