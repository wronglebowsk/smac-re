#!/usr/bin/env python3
"""Parse alpha.txt (SMAC's user-editable rules file) into JSON.

alpha.txt is a `#SECTION` list of comma-separated records, one record per line, with
`;` comments trailing every field. The exe just loads this file, so these tables are the
game's balance data — a reimplementation should read the file, not the exe.

    scripts/parse_alpha.py                       # -> data/alpha.json + summary
    scripts/parse_alpha.py --section UNITS       # dump one section as JSON
    scripts/parse_alpha.py --summary             # counts/widths only

Caveat: field *semantics* are only known where the trailing comment says so (the
comments are, conveniently, the schema). `--with-comments` keeps them.
"""
import argparse
import json
import os
import re
import sys
from collections import Counter, OrderedDict

SRC = os.path.expanduser("~/reverse/smac/programs/alpha.txt")
OUT = os.path.expanduser("~/reverse/smac/data/alpha.json")

SEC_RE = re.compile(r"^#(\w+)\s*$")


def split_comment(line):
    """Return (payload, comment). Semicolons start comments; they never appear in text
    fields in this file (checked: no quoted strings contain ';')."""
    if ";" in line:
        payload, comment = line.split(";", 1)
        return payload, comment.strip()
    return line, ""


def parse(path, keep_comments=False):
    sections = OrderedDict()
    cur = None
    for raw in open(path, encoding="latin-1"):
        line = raw.rstrip("\r\n")
        m = SEC_RE.match(line.strip())
        if m:
            cur = m.group(1)
            sections.setdefault(cur, [])
            continue
        if cur is None or not line.strip() or line.lstrip().startswith(";"):
            continue
        payload, comment = split_comment(line)
        fields = [f.strip() for f in payload.split(",")]
        while fields and fields[-1] == "":
            fields.pop()
        if not fields:
            continue
        rec = {"fields": fields}
        # The comments ARE the schema: one comment per field, comma-separated too.
        # Attach a name only when the counts agree (they do for most sections).
        names = [c.strip() for c in comment.split(",")] if comment else []
        while names and names[-1] == "":
            names.pop()
        if len(names) == len(fields):
            rec["names"] = names
        elif keep_comments and comment:
            rec["comment"] = comment
        sections[cur].append(rec)
    return sections


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=SRC)
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--section", help="dump one section to stdout")
    ap.add_argument("--summary", action="store_true")
    ap.add_argument("--with-comments", action="store_true")
    ap.add_argument("--md", help="also write a markdown section table here")
    a = ap.parse_args()

    if not os.path.exists(a.src):
        sys.exit(f"no alpha.txt at {a.src}")

    secs = parse(a.src, a.with_comments)

    if a.section:
        want = a.section.upper()
        if want not in secs:
            sys.exit("sections: " + ", ".join(secs))
        print(json.dumps({want: secs[want]}, indent=1)[:4000])
        return

    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        json.dump(secs, f, indent=1)

    # schema = the mode of the per-field name lists seen in each section
    schema = {}
    for name, recs in secs.items():
        lists = [tuple(r["names"]) for r in recs if "names" in r]
        if lists:
            schema[name] = list(Counter(lists).most_common(1)[0][0])
    schema_path = os.path.join(os.path.dirname(a.out), "alpha_schema.json")
    with open(schema_path, "w") as f:
        json.dump(schema, f, indent=1)

    total = sum(len(v) for v in secs.values())
    print(f"{len(secs)} sections, {total} records -> {a.out}")
    print(f"field names recovered for {len(schema)}/{len(secs)} sections -> {schema_path}")
    if a.summary or True:
        print(f"{'section':<14}{'records':>8}  widths")
        for name, recs in secs.items():
            widths = Counter(len(r["fields"]) for r in recs)
            w = " ".join(f"{k}f×{v}" for k, v in sorted(widths.items()))
            print(f"{name:<14}{len(recs):>8}  {w}")
        if a.md:
            with open(a.md, "w") as f:
                f.write("# alpha.txt — section map\n\n")
                f.write(f"Generated by `scripts/parse_alpha.py` from `programs/alpha.txt`: "
                        f"**{len(secs)} sections, {total} records**.\n\n")
                f.write("Widths are field counts; a section with more than one width mixes "
                        "record shapes (list headers, blank sentinels) and needs care.\n\n")
                f.write("| section | records | field widths | schema from comments? | first record |\n")
                f.write("|---|---|---|---|---|\n")
                for name, recs in secs.items():
                    widths = Counter(len(r_["fields"]) for r_ in recs)
                    w = ", ".join(f"{k}f×{v}" for k, v in sorted(widths.items()))
                    first = " | ".join(recs[0]["fields"][:6]) if recs else ""
                    f.write(f"| `{name}` | {len(recs)} | {w} | "
                            f"{'yes' if name in schema else 'no'} | {first[:80]} |\n")
                f.write("\nRecords and full text: `data/alpha.json`.\n")
            print(f"wrote {a.md}")


if __name__ == "__main__":
    main()
